import type { CallistoEdge, CallistoNode, DiagramPage } from '../types/diagram';
import { createId } from '../utils/ids';
import { buildNodeFromShape } from '../store/diagramStore';

export type CodeFormat = 'mermaid' | 'plantuml' | 'dot' | 'json';

function safeId(id: string): string {
  return id.replace(/[^a-zA-Z0-9_]/g, '_');
}

export function exportPageToCode(page: DiagramPage, format: CodeFormat): string {
  if (format === 'json') {
    return JSON.stringify(page, null, 2);
  }

  if (format === 'dot') {
    const lines = ['digraph CallistoDiagram {', '  rankdir=TB;', '  node [shape=box, fontname="Inter"];'];
    for (const n of page.nodes) {
      const label = (n.data.label || n.id).replace(/"/g, '\\"');
      lines.push(`  "${safeId(n.id)}" [label="${label}"];`);
    }
    for (const e of page.edges) {
      const labelAttr = e.data?.label ? ` [label="${e.data.label.replace(/"/g, '\\"')}"]` : '';
      lines.push(`  "${safeId(e.source)}" -> "${safeId(e.target)}"${labelAttr};`);
    }
    lines.push('}');
    return lines.join('\n');
  }

  if (format === 'plantuml') {
    const lines = ['@startuml', `' Generated by Callisto (AkashaVyom Labs)`, 'skinparam shadowing false'];
    if (page.diagramType === 'uml-class') {
      for (const n of page.nodes) {
        if (n.data.shapeKind === 'uml-class' || n.data.shapeKind === 'uml-interface') {
          const kw = n.data.shapeKind === 'uml-interface' ? 'interface' : 'class';
          lines.push(`${kw} "${n.data.label}" as ${safeId(n.id)} {`);
          for (const a of n.data.umlClass?.attributes ?? []) {
            lines.push(`  ${a.visibility}${a.name}: ${a.type}`);
          }
          for (const m of n.data.umlClass?.methods ?? []) {
            lines.push(`  ${m.visibility}${m.name}(${m.params}): ${m.returnType}`);
          }
          lines.push('}');
        } else {
          lines.push(`rectangle "${n.data.label}" as ${safeId(n.id)}`);
        }
      }
    } else {
      for (const n of page.nodes) {
        lines.push(`rectangle "${n.data.label}" as ${safeId(n.id)}`);
      }
    }
    for (const e of page.edges) {
      const arrow = e.data?.lineStyle === 'dashed' ? '..>' : '-->';
      const lbl = e.data?.label ? ` : ${e.data.label}` : '';
      lines.push(`${safeId(e.source)} ${arrow} ${safeId(e.target)}${lbl}`);
    }
    lines.push('@enduml');
    return lines.join('\n');
  }

  // Mermaid
  if (page.diagramType === 'uml-class') {
    const lines = ['classDiagram'];
    for (const n of page.nodes) {
      const clsName = safeId(n.data.label || n.id);
      lines.push(`  class ${clsName} {`);
      for (const a of n.data.umlClass?.attributes ?? []) {
        lines.push(`    ${a.visibility}${a.type} ${a.name}`);
      }
      for (const m of n.data.umlClass?.methods ?? []) {
        lines.push(`    ${m.visibility}${m.name}(${m.params}) ${m.returnType}`);
      }
      lines.push('  }');
    }
    const idToName = new Map(page.nodes.map((n) => [n.id, safeId(n.data.label || n.id)]));
    for (const e of page.edges) {
      const s = idToName.get(e.source) ?? safeId(e.source);
      const t = idToName.get(e.target) ?? safeId(e.target);
      const rel =
        e.data?.umlRelationship === 'generalization'
          ? '<|--'
          : e.data?.umlRelationship === 'composition'
            ? '*--'
            : e.data?.umlRelationship === 'aggregation'
              ? 'o--'
              : e.data?.umlRelationship === 'realization'
                ? '<|..'
                : '-->';
      const lbl = e.data?.label ? ` : ${e.data.label}` : '';
      lines.push(`  ${s} ${rel} ${t}${lbl}`);
    }
    return lines.join('\n');
  }

  if (page.diagramType === 'er-diagram') {
    const lines = ['erDiagram'];
    const idToTable = new Map<string, string>();
    for (const n of page.nodes) {
      const tName = safeId(n.data.erEntity?.tableName || n.data.label || n.id).toUpperCase();
      idToTable.set(n.id, tName);
      lines.push(`  ${tName} {`);
      for (const col of n.data.erEntity?.columns ?? []) {
        const keyTag = col.isPrimaryKey ? ' PK' : col.isForeignKey ? ' FK' : '';
        lines.push(`    ${col.dataType.replace(/\s+/g, '_')} ${col.name}${keyTag}`);
      }
      lines.push('  }');
    }
    for (const e of page.edges) {
      const s = idToTable.get(e.source) ?? safeId(e.source);
      const t = idToTable.get(e.target) ?? safeId(e.target);
      lines.push(`  ${s} ||--o{ ${t} : "${e.data?.label || 'relates'}"`);
    }
    return lines.join('\n');
  }

  const lines = ['flowchart TD'];
  for (const n of page.nodes) {
    const sid = safeId(n.id);
    const lbl = (n.data.label || n.id).replace(/"/g, "'");
    if (n.data.shapeKind === 'fc-decision' || n.data.shapeKind === 'diamond') {
      lines.push(`  ${sid}{"${lbl}"}`);
    } else if (n.data.shapeKind === 'fc-start-end' || n.data.shapeKind === 'rounded-rect') {
      lines.push(`  ${sid}("${lbl}")`);
    } else {
      lines.push(`  ${sid}["${lbl}"]`);
    }
  }
  for (const e of page.edges) {
    const s = safeId(e.source);
    const t = safeId(e.target);
    const arrow = e.data?.lineStyle === 'dashed' ? '-.->' : '-->';
    const lbl = e.data?.label ? `|"${e.data.label}"|` : '';
    lines.push(`  ${s} ${arrow}${lbl} ${t}`);
  }
  return lines.join('\n');
}

export interface CodeImportResult {
  nodes: CallistoNode[];
  edges: CallistoEdge[];
  warnings: string[];
}

export function parseCodeToGraph(
  source: string,
  format: CodeFormat,
  layerId: string
): CodeImportResult {
  const warnings: string[] = [];

  if (format === 'json') {
    const parsed = JSON.parse(source) as Partial<DiagramPage>;
    return {
      nodes: parsed.nodes ?? [],
      edges: parsed.edges ?? [],
      warnings: parsed.nodes ? [] : ['JSON did not contain a nodes array.'],
    };
  }

  if (format === 'dot') {
    const nodes: CallistoNode[] = [];
    const edges: CallistoEdge[] = [];
    const nodeMap = new Map<string, CallistoNode>();

    const ensureNode = (rawId: string, label?: string) => {
      const key = rawId.trim().replace(/^"|"$/g, '');
      if (!nodeMap.has(key)) {
        const idx = nodeMap.size;
        const node = buildNodeFromShape(
          'rectangle',
          { x: 100 + (idx % 4) * 210, y: 80 + Math.floor(idx / 4) * 130 },
          layerId,
          { label: label || key }
        );
        nodeMap.set(key, node);
        nodes.push(node);
      } else if (label) {
        nodeMap.get(key)!.data.label = label;
      }
      return nodeMap.get(key)!;
    };

    for (const line of source.split('\n')) {
      const edgeMatch = /^\s*"?([a-zA-Z0-9_]+)"?\s*->\s*"?([a-zA-Z0-9_]+)"?(?:\s*\[label="([^"]*)"\])?/.exec(line);
      if (edgeMatch) {
        const src = ensureNode(edgeMatch[1]);
        const tgt = ensureNode(edgeMatch[2]);
        edges.push({
          id: createId('edge'),
          source: src.id,
          target: tgt.id,
          type: 'callisto',
          data: {
            connectorType: 'orthogonal',
            lineStyle: 'solid',
            strokeColor: '#334155',
            strokeWidth: 1.5,
            arrowStart: 'none',
            arrowEnd: 'filled-arrow',
            label: edgeMatch[3],
          },
        });
        continue;
      }
      const nodeMatch = /^\s*"?([a-zA-Z0-9_]+)"?\s*\[label="([^"]*)"\]/.exec(line);
      if (nodeMatch) {
        ensureNode(nodeMatch[1], nodeMatch[2]);
      }
    }
    return { nodes, edges, warnings };
  }

  // Mermaid flowchart / basic parser
  const nodes: CallistoNode[] = [];
  const edges: CallistoEdge[] = [];
  const nodeMap = new Map<string, CallistoNode>();

  const ensureMermaidNode = (rawToken: string) => {
    const token = rawToken.trim();
    const match = /^([a-zA-Z0-9_]+)(?:\["?([^"\]]+)"?\]|\("?([^")]+)"?\)|\{"?([^"}]+)"?\})?/.exec(token);
    const key = match?.[1] ?? token;
    const label = match?.[2] ?? match?.[3] ?? match?.[4] ?? key;
    const shapeKind = match?.[4]
      ? 'fc-decision'
      : match?.[3]
        ? 'fc-start-end'
        : 'fc-process';

    if (!nodeMap.has(key)) {
      const idx = nodeMap.size;
      const node = buildNodeFromShape(
        shapeKind,
        { x: 100 + (idx % 3) * 220, y: 80 + Math.floor(idx / 3) * 130 },
        layerId,
        { label }
      );
      nodeMap.set(key, node);
      nodes.push(node);
    }
    return nodeMap.get(key)!;
  };

  for (const rawLine of source.split('\n')) {
    const line = rawLine.trim();
    if (!line || line.startsWith('%%') || /^(flowchart|graph|sequenceDiagram|classDiagram|erDiagram)\b/.test(line)) {
      continue;
    }
    const edgeMatch = /^(.+?)\s*(-->|-\.->|==>)(?:\|"?([^"|]+)"?\|)?\s*(.+)$/.exec(line);
    if (edgeMatch) {
      const src = ensureMermaidNode(edgeMatch[1]);
      const tgt = ensureMermaidNode(edgeMatch[4]);
      edges.push({
        id: createId('edge'),
        source: src.id,
        target: tgt.id,
        type: 'callisto',
        data: {
          connectorType: 'orthogonal',
          lineStyle: edgeMatch[2] === '-.->' ? 'dashed' : 'solid',
          strokeColor: '#334155',
          strokeWidth: 1.5,
          arrowStart: 'none',
          arrowEnd: 'filled-arrow',
          label: edgeMatch[3],
        },
      });
    } else if (/^[a-zA-Z0-9_]+(\[|\(|\{)/.test(line)) {
      ensureMermaidNode(line);
    }
  }

  if (nodes.length === 0) {
    warnings.push('No convertible Mermaid nodes found. Complex sequence/gantt syntax renders in preview mode.');
  }

  return { nodes, edges, warnings };
}

