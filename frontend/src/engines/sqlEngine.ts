import type { CallistoEdge, CallistoNode, ERColumn, ERDialect } from '../types/diagram';
import { createId } from '../utils/ids';
import { buildNodeFromShape } from '../store/diagramStore';

function quoteIdent(name: string, dialect: ERDialect): string {
  const clean = name.replace(/[`"\[\]]/g, '');
  if (dialect === 'mysql') return `\`${clean}\``;
  if (dialect === 'mssql') return `[${clean}]`;
  return `"${clean}"`;
}

export function generateSQLFromNodes(
  nodes: CallistoNode[],
  dialect: ERDialect = 'postgresql'
): string {
  const erNodes = nodes.filter(
    (n) => n.data.shapeKind === 'er-table' || n.data.shapeKind === 'er-document'
  );

  if (erNodes.length === 0) {
    return '-- No ER tables or MongoDB document nodes found on the current page.';
  }

  if (dialect === 'mongodb') {
    const collections = erNodes.map((n) => {
      const entity = n.data.erEntity;
      const props: Record<string, { bsonType: string; description?: string }> = {};
      const required: string[] = [];
      for (const col of entity?.columns ?? []) {
        props[col.name] = {
          bsonType: col.dataType.toLowerCase().includes('int')
            ? 'int'
            : col.dataType.toLowerCase().includes('bool')
              ? 'bool'
              : col.dataType.toLowerCase().includes('objectid')
                ? 'objectId'
                : 'string',
          ...(col.description ? { description: col.description } : {}),
        };
        if (!col.isNullable) required.push(col.name);
      }
      return {
        collection: entity?.tableName || n.data.label,
        validator: {
          $jsonSchema: {
            bsonType: 'object',
            required,
            properties: props,
          },
        },
      };
    });
    return JSON.stringify(collections, null, 2);
  }

  const statements: string[] = [
    `-- Generated by Callisto (AkashaVyom Labs) — Dialect: ${dialect.toUpperCase()}`,
    '',
  ];

  for (const node of erNodes) {
    const entity = node.data.erEntity;
    if (!entity) continue;
    const table = quoteIdent(entity.tableName || node.data.label, dialect);
    const lines: string[] = [];
    const pkCols: string[] = [];
    const fkLines: string[] = [];
    const indexLines: string[] = [];

    for (const col of entity.columns) {
      const colIdent = quoteIdent(col.name, dialect);
      const parts = [colIdent, col.dataType || 'VARCHAR(255)'];
      if (col.isNullable === false) parts.push('NOT NULL');
      if (col.isUnique && !col.isPrimaryKey) parts.push('UNIQUE');
      if (col.defaultValue) parts.push(`DEFAULT ${col.defaultValue}`);
      lines.push(`  ${parts.join(' ')}`);

      if (col.isPrimaryKey) pkCols.push(colIdent);
      if (col.isForeignKey && col.referencesTable) {
        const refTable = quoteIdent(col.referencesTable, dialect);
        const refCol = quoteIdent(col.referencesColumn || 'id', dialect);
        fkLines.push(
          `  FOREIGN KEY (${colIdent}) REFERENCES ${refTable}(${refCol})`
        );
      }
      if (col.isIndexed && !col.isPrimaryKey) {
        indexLines.push(
          `CREATE INDEX ${quoteIdent(`idx_${entity.tableName}_${col.name}`, dialect)} ON ${table} (${colIdent});`
        );
      }
    }

    if (pkCols.length > 0) {
      lines.push(`  PRIMARY KEY (${pkCols.join(', ')})`);
    }
    lines.push(...fkLines);

    statements.push(`CREATE TABLE ${table} (`);
    statements.push(lines.join(',\n'));
    statements.push(');');
    if (indexLines.length > 0) {
      statements.push(...indexLines);
    }
    statements.push('');
  }

  return statements.join('\n');
}

export interface ParsedSQLResult {
  nodes: CallistoNode[];
  edges: CallistoEdge[];
  warnings: string[];
}

export function parseSQLToERDiagram(
  sql: string,
  layerId: string,
  dialect: ERDialect = 'postgresql'
): ParsedSQLResult {
  const warnings: string[] = [];
  const tableRegex =
    /CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?[`"\[]?([a-zA-Z0-9_]+)[`"\]]?\s*\(([\s\S]*?)\)\s*;/gi;

  const nodes: CallistoNode[] = [];
  const tableNodeMap = new Map<string, CallistoNode>();
  const fkRelations: Array<{ fromTable: string; toTable: string; colName: string }> = [];

  let match: RegExpExecArray | null;
  let index = 0;

  while ((match = tableRegex.exec(sql)) !== null) {
    const tableName = match[1];
    const body = match[2];
    const rawLines = splitTopLevelCommas(body);
    const columns: ERColumn[] = [];
    const tablePKs = new Set<string>();

    for (const raw of rawLines) {
      const line = raw.trim();
      if (!line) continue;

      const pkMatch = /^PRIMARY\s+KEY\s*\(([^)]+)\)/i.exec(line);
      if (pkMatch) {
        pkMatch[1]
          .split(',')
          .map((s) => s.trim().replace(/[`"\[\]]/g, ''))
          .forEach((c) => tablePKs.add(c));
        continue;
      }

      const fkMatch =
        /^(?:CONSTRAINT\s+[`"\[]?[a-zA-Z0-9_]+[`"\]]?\s+)?FOREIGN\s+KEY\s*\([`"\[]?([a-zA-Z0-9_]+)[`"\]]?\)\s*REFERENCES\s+[`"\[]?([a-zA-Z0-9_]+)[`"\]]?(?:\s*\([`"\[]?([a-zA-Z0-9_]+)[`"\]]?\))?/i.exec(
          line
        );
      if (fkMatch) {
        fkRelations.push({
          fromTable: tableName,
          toTable: fkMatch[2],
          colName: fkMatch[1],
        });
        const existing = columns.find((c) => c.name === fkMatch[1]);
        if (existing) {
          existing.isForeignKey = true;
          existing.referencesTable = fkMatch[2];
          existing.referencesColumn = fkMatch[3] || 'id';
        }
        continue;
      }

      if (/^(UNIQUE|CHECK|INDEX|KEY|CONSTRAINT)\b/i.test(line)) {
        continue;
      }

      const colMatch =
        /^[`"\[]?([a-zA-Z0-9_]+)[`"\]]?\s+([a-zA-Z0-9_]+(?:\s*\([^)]+\))?)(.*)$/i.exec(
          line
        );
      if (colMatch) {
        const colName = colMatch[1];
        const dataType = colMatch[2].toUpperCase();
        const rest = colMatch[3] || '';
        const isPrimaryKey = /PRIMARY\s+KEY/i.test(rest);
        const isUnique = /UNIQUE/i.test(rest);
        const isNullable = !/NOT\s+NULL/i.test(rest);
        const inlineRef = /REFERENCES\s+[`"\[]?([a-zA-Z0-9_]+)[`"\]]?(?:\s*\([`"\[]?([a-zA-Z0-9_]+)[`"\]]?\))?/i.exec(rest);

        if (inlineRef) {
          fkRelations.push({
            fromTable: tableName,
            toTable: inlineRef[1],
            colName,
          });
        }

        columns.push({
          id: createId('col'),
          name: colName,
          dataType,
          isPrimaryKey,
          isForeignKey: Boolean(inlineRef),
          isUnique,
          isNullable,
          referencesTable: inlineRef?.[1],
          referencesColumn: inlineRef?.[2] || (inlineRef ? 'id' : undefined),
        });
      }
    }

    for (const col of columns) {
      if (tablePKs.has(col.name)) col.isPrimaryKey = true;
    }

    const colIdx = index % 3;
    const rowIdx = Math.floor(index / 3);
    const node = buildNodeFromShape(
      'er-table',
      { x: 80 + colIdx * 290, y: 80 + rowIdx * 240 },
      layerId,
      {
        label: tableName,
        erEntity: {
          tableName,
          dialect,
          columns,
        },
      }
    );
    nodes.push(node);
    tableNodeMap.set(tableName.toLowerCase(), node);
    index += 1;
  }

  if (nodes.length === 0) {
    warnings.push('No valid CREATE TABLE (...); statements were detected.');
  }

  const edges: CallistoEdge[] = [];
  for (const rel of fkRelations) {
    const src = tableNodeMap.get(rel.fromTable.toLowerCase());
    const tgt = tableNodeMap.get(rel.toTable.toLowerCase());
    if (src && tgt) {
      edges.push({
        id: createId('edge'),
        source: src.id,
        target: tgt.id,
        type: 'callisto',
        data: {
          connectorType: 'orthogonal',
          lineStyle: 'solid',
          strokeColor: '#334155',
          strokeWidth: 1.5,
          arrowStart: 'crows-foot-many',
          arrowEnd: 'crows-foot-one',
          label: rel.colName,
          erCardinality: '1:N',
        },
      });
    } else {
      warnings.push(`Referenced table "${rel.toTable}" not found in imported SQL.`);
    }
  }

  return { nodes, edges, warnings };
}

function splitTopLevelCommas(input: string): string[] {
  const parts: string[] = [];
  let current = '';
  let depth = 0;
  for (const ch of input) {
    if (ch === '(') depth += 1;
    else if (ch === ')' && depth > 0) depth -= 1;
    if (ch === ',' && depth === 0) {
      parts.push(current);
      current = '';
    } else {
      current += ch;
    }
  }
  if (current.trim()) parts.push(current);
  return parts;
}

